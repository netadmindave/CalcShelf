// Builds app/www/data/giacunits.js: which unit names Giac (the CAS) understands exactly as CalcShelf's unit engine does.
// Giac reads an unknown unit as a prefix plus another unit (_Da → deca·are, _kn → kilo·n), so every name is checked
// against the engine's own value. Names Giac gets wrong are sent to it in SI form, or under Giac's own name for that unit.
// Usage: node core-build/units/gen_giacunits.js app/www/data/giacunits.js
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const Units = require(path.join(ROOT, 'app/www/js/units.js'));
const giac = require(path.join(ROOT, 'tests/giacnode.js'));
const PREFIXES = ['Q', 'R', 'Y', 'Z', 'E', 'P', 'T', 'G', 'M', 'k', 'h', 'da', 'd', 'c', 'm', 'µ', 'n', 'p', 'f', 'a', 'z', 'y', 'r', 'q'];
// Giac's own names to try for units it spells differently
const GIAC_NAMES = ['Angstrom', 'Ang', 'lyr', 'hr', 'knot', 'Ohm', 'deg', 'arcmin', 'arcs', 'Btu', 'ozfl', 'fath', 'fur', 'chain', 'rod', 'acre', 'tonUK', 'tonUS', 'lbt', 'ozUK', 'galUK', 'galC', 'liqpt', 'cu', 'tbsp', 'tsp', 'bbl', 'bu', 'pk', 'mph', 'kph', 'ftUS', 'miUS', 'mil', 'mile', 'yd', 'au', 'pc', 'cal', 'kcal', 'eV', 'therm', 'erg', 'hp', 'atm', 'bar', 'mmHg', 'inHg', 'inH2O', 'torr', 'psi', 'Torr', 'dyn', 'gf', 'kip', 'lbf', 'pdl', 'grad', 'rpm', 'Ci', 'R', 'rem', 'rd', 'Gy', 'Sv', 'Bq', 'gal', 'qt', 'pt', 'cup', 'oz', 'lb', 'ct', 'grain', 'u', 'slug', 'st', 'ha', 'b', 'a', 'L', 'l', 'ml', 'mn', 'h', 'd', 'yr', 'min', 'Wh', 'kWh', 'G', 'Gal', 'Oe', 'P', 'St', 'lam', 'ph', 'sb', 'flam', 'fc', 'lx', 'lm', 'cd', 'sr', 'Hz', 'tec', 'FF', 'Fdy', 'c', 'D'];
const BASE_I = { m: 0, kg: 1, s: 2, A: 3, K: 4, mol: 5, cd: 6, rad: 7 };
function giacDims(r) {
  // "6894.75_(kg*m^-1.0*s^-2.0)" or "1e-06_m" or "0.0174532925199"
  const m = String(r).match(/^\s*(-?[\d.]+(?:e[-+]?\d+)?)\s*(?:\*?\s*_\(?([^)]*)\)?)?\s*$/);
  if (!m) return null;
  const d = new Array(9).fill(0);
  if (m[2]) for (const t of m[2].split('*')) { const mm = t.trim().match(/^(\w+)(?:\^\(?(-?[\d.]+)\)?)?$/); if (!mm || !(mm[1] in BASE_I)) return null; d[BASE_I[mm[1]]] += mm[2] ? +mm[2] : 1; }
  return { v: +m[1], d };
}
const same = (a, b) => a.every((x, i) => i === 7 || Math.abs(x - b[i]) < 1e-9);   // Giac's angles are plain numbers
(async () => {
  let ev = await giac();
  // a few names crash this Giac build: restart it and treat the name as unknown
  const test = async (tok) => { let r; try { r = ev('evalf(mksa(1_' + tok + '))'); } catch (e) { ev = await giac(); return null; } if (/ERROR|Error|"/.test(r)) return null; return giacDims(r); };
  const ok = new Set(), alias = {};
  const names = new Set(Object.keys(Units.U).filter((k) => !/['"′″%‰]/.test(k)));
  const candidates = [];
  for (const k of names) { candidates.push(k); if (Units.U[k].px) for (const p of PREFIXES) candidates.push(p + k); }
  const giacCache = {};
  const gt = async (t) => (t in giacCache ? giacCache[t] : (giacCache[t] = /^[A-Za-z0-9µΩÅ°_]+$/.test(t) ? await test(t) : null));
  for (const tok of candidates) {
    const ours = Units.lookup(tok); if (!ours) continue;
    if (ours.d[8] || ours.d[6]) continue;                      // bits and candelas: Giac has neither
    const g = await gt(tok);
    if (g && same(g.d, ours.d) && Math.abs(g.v / ours.f - 1) < 1e-7) { ok.add(tok); continue; }
    // another spelling Giac knows (prefix + Giac name)
    const base = Units.U[tok] ? tok : PREFIXES.map((p) => (tok.startsWith(p) && Units.U[tok.slice(p.length)] ? [p, tok.slice(p.length)] : null)).filter(Boolean).sort((x, y) => y[0].length - x[0].length)[0];
    const [px, b] = typeof base === 'string' ? ['', base] : base || ['', tok];
    const spellings = [...Object.keys(Units.U).filter((k) => Units.U[k] === Units.U[b]), ...GIAC_NAMES];
    for (const sp of spellings) {
      const t2 = px + sp; if (t2 === tok) continue;
      const g2 = await gt(t2);
      if (!(g2 && same(g2.d, ours.d) && Math.abs(g2.v / ours.f - 1) < 1e-7)) continue;
      // the result comes back under Giac's name, so that name must mean the same unit to CalcShelf (Giac's _rd is rad, ours is rod)
      const back = Units.lookup(t2);
      if (back && !(Units.sameDim(back.d, ours.d) && Math.abs(back.f / ours.f - 1) < 1e-9)) continue;
      if (/Bd$/.test(tok)) break;                                      // baud is not becquerel, even if Giac agrees on 1/s
      alias[tok] = t2; break;
    }
  }
  const out = '/* Generated by core-build/units/gen_giacunits.js — unit names Giac reads exactly as CalcShelf does, and Giac\'s spelling for others. */\n' +
    'self.GIAC_UNITS = { ok: ' + JSON.stringify([...ok].sort()) + ',\n  alias: ' + JSON.stringify(alias) + ' };\n';
  fs.writeFileSync(process.argv[2] || path.join(ROOT, 'app/www/data/giacunits.js'), out);
  console.log('ok', ok.size, 'alias', Object.keys(alias).length, 'of', candidates.length);
})();
